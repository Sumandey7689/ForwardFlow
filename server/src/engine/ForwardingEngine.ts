import { prisma } from '../config/prisma.js';
import { WhatsAppProviderFactory } from '../whatsapp/WhatsAppProviderFactory.js';
import { IWhatsAppProvider } from '../whatsapp/IWhatsAppProvider.js';
import {
  NormalizedMessage,
  MessageTypeConfiguration,
  ScheduleConfiguration,
} from '../types/index.js';
import { generateIdempotencyKey } from '../utils/crypto.js';
import { forwardingQueue } from './ForwardingQueue.js';
import { emitToAdmin } from '../socket/socketManager.js';
import { logger } from '../config/logger.js';

export class ForwardingEngine {
  private static isInitialized = false;
  private static automatedMessageIds = new Set<string>();

  public static registerAutomatedMessageId(messageId: string): void {
    if (!messageId) return;
    this.automatedMessageIds.add(messageId);
    if (this.automatedMessageIds.size > 20000) {
      const iter = this.automatedMessageIds.values();
      for (let i = 0; i < 5000; i++) {
        const next = iter.next();
        if (next.done) break;
        this.automatedMessageIds.delete(next.value);
      }
    }
  }

  public static isAutomatedMessageId(messageId: string): boolean {
    if (!messageId) return false;
    return this.automatedMessageIds.has(messageId);
  }

  public static initialize(): void {
    if (this.isInitialized) return;
    this.isInitialized = true;

    // Register queue processor
    import('./ForwardingWorker.js').then(({ processForwardingJob }) => {
      forwardingQueue.registerProcessor(processForwardingJob);
    });

    logger.info('Forwarding Engine initialized');
  }

  /**
   * Bind an active provider to the forwarding engine
   */
  public static bindProvider(provider: IWhatsAppProvider, adminId: string): void {
    provider.onMessage(async (message: NormalizedMessage) => {
      await this.handleIncomingMessage(message, adminId);
    });

    provider.onStatus(async (status, error) => {
      try {
        await prisma.whatsAppAccount.update({
          where: { id: provider.accountId },
          data: {
            connectionStatus: status,
            lastConnectedAt: status === 'CONNECTED' ? new Date() : undefined,
          },
        });

        emitToAdmin(adminId, 'whatsapp:connection-status', {
          accountId: provider.accountId,
          status,
          error,
        });
      } catch (err: any) {
        logger.error({ accountId: provider.accountId, err: err.message }, 'Failed to update account status in DB');
      }
    });

    provider.onQr((qrCodeDataUrl) => {
      emitToAdmin(adminId, 'whatsapp:qr-code', {
        accountId: provider.accountId,
        qrCode: qrCodeDataUrl,
      });
    });

    logger.info({ accountId: provider.accountId, adminId }, 'Provider successfully bound to Forwarding Engine');
  }

  /**
   * Process incoming message event through rule evaluation and queue creation
   */
  public static async handleIncomingMessage(
    message: NormalizedMessage,
    adminId: string
  ): Promise<void> {
    try {
      // 1. Loop Prevention: Drop automated forward echoes sent by ForwardFlow
      if (message.fromMe) {
        if (this.isAutomatedMessageId(message.id)) {
          logger.debug({ messageId: message.id }, 'Ignored automated forward echo generated by ForwardFlow');
          return;
        }

        const existingJob = await prisma.forwardingJob.findFirst({
          where: { providerSentMessageId: message.id },
          select: { id: true },
        });

        if (existingJob) {
          this.registerAutomatedMessageId(message.id);
          logger.debug({ messageId: message.id }, 'Ignored message matching existing providerSentMessageId');
          return;
        }
      }

      // 2. Locate source conversation in database
      const rawSourceJid = message.sourceJid;
      const cleanDigits = rawSourceJid.replace(/@.*$/, '').replace(/\D/g, '');

      const orConditions: any[] = [
        { providerConversationId: rawSourceJid },
      ];

      if (cleanDigits) {
        orConditions.push(
          { providerConversationId: `${cleanDigits}@s.whatsapp.net` },
          { providerConversationId: `+${cleanDigits}@s.whatsapp.net` }
        );
        if (cleanDigits.startsWith('91') && cleanDigits.length === 12) {
          const tenDigits = cleanDigits.slice(2);
          orConditions.push(
            { providerConversationId: `${tenDigits}@s.whatsapp.net` },
            { providerConversationId: `+${tenDigits}@s.whatsapp.net` }
          );
        } else if (cleanDigits.length === 10) {
          orConditions.push(
            { providerConversationId: `91${cleanDigits}@s.whatsapp.net` },
            { providerConversationId: `+91${cleanDigits}@s.whatsapp.net` }
          );
        }
      }

      let sourceConversation = await prisma.conversation.findFirst({
        where: {
          whatsappAccountId: message.accountId,
          OR: orConditions,
        },
      });

      // If untracked individual chat, auto-register it so it can be monitored / forwarded
      if (!sourceConversation && !rawSourceJid.endsWith('@g.us') && cleanDigits) {
        const canonicalDigits = cleanDigits.length === 10 ? `91${cleanDigits}` : cleanDigits;
        const canonicalJid = `${canonicalDigits}@s.whatsapp.net`;
        const formattedName =
          message.senderName ||
          (canonicalDigits.startsWith('91') && canonicalDigits.length === 12
            ? `+91 ${canonicalDigits.slice(2, 7)} ${canonicalDigits.slice(7)}`
            : `+${canonicalDigits}`);

        sourceConversation = await prisma.conversation.upsert({
          where: {
            whatsappAccountId_providerConversationId: {
              whatsappAccountId: message.accountId,
              providerConversationId: canonicalJid,
            },
          },
          update: {
            name: message.senderName || formattedName,
            canReceiveMessages: true,
            canSendMessages: true,
            lastActivityAt: new Date(),
          },
          create: {
            whatsappAccountId: message.accountId,
            providerConversationId: canonicalJid,
            name: formattedName,
            conversationType: 'INDIVIDUAL',
            canReceiveMessages: true,
            canSendMessages: true,
            lastActivityAt: new Date(),
            capabilityMetadata: JSON.stringify({
              phoneNumber: canonicalDigits,
              formattedPhone: formattedName,
              isPersonalNumber: true,
            }),
          },
        });
      }

      if (!sourceConversation) {
        // Message from untracked conversation
        return;
      }

      // 3. Persist incoming message (safely handle duplicates)
      let incomingMessageRecord = await prisma.incomingMessage.findUnique({
        where: {
          whatsappAccountId_sourceConversationId_providerMessageId: {
            whatsappAccountId: message.accountId,
            sourceConversationId: sourceConversation.id,
            providerMessageId: message.id,
          },
        },
      });

      if (!incomingMessageRecord) {
        incomingMessageRecord = await prisma.incomingMessage.create({
          data: {
            whatsappAccountId: message.accountId,
            sourceConversationId: sourceConversation.id,
            providerMessageId: message.id,
            senderId: message.senderJid,
            senderName: message.senderName,
            messageType: message.messageType,
            textBody: message.textBody,
            contentReference: message.rawPayload ? JSON.stringify(message.rawPayload) : null,
            receivedAt: message.timestamp,
          },
        });

        emitToAdmin(adminId, 'forwarding:message-received', {
          message: incomingMessageRecord,
        });
      }

      // 4. Find all active forwarding rules for this conversation
      // A) Direct rules where this conversation is the source
      const directRules = await prisma.forwardingRule.findMany({
        where: {
          whatsappAccountId: message.accountId,
          sourceConversationId: sourceConversation.id,
          enabled: true,
        },
        include: {
          sourceConversation: true,
          destinations: {
            where: { enabled: true },
            include: { destinationConversation: true },
          },
        },
      });

      // B) Bidirectional rules where this conversation is one of the destinations
      const bidirectionalRules = await prisma.forwardingRule.findMany({
        where: {
          whatsappAccountId: message.accountId,
          enabled: true,
          bidirectional: true,
          destinations: {
            some: {
              destinationConversationId: sourceConversation.id,
              enabled: true,
            },
          },
        },
        include: {
          sourceConversation: true,
          destinations: {
            where: { enabled: true },
            include: { destinationConversation: true },
          },
        },
      });

      const ruleTasks: Array<{
        rule: typeof directRules[0];
        targetConversations: typeof sourceConversation[];
        isReverse: boolean;
      }> = [];

      for (const rule of directRules) {
        ruleTasks.push({
          rule,
          targetConversations: rule.destinations.map((d) => d.destinationConversation),
          isReverse: false,
        });
      }

      for (const rule of bidirectionalRules) {
        ruleTasks.push({
          rule,
          targetConversations: [rule.sourceConversation],
          isReverse: true,
        });
      }

      if (ruleTasks.length === 0) {
        return;
      }

      for (const task of ruleTasks) {
        const { rule, targetConversations, isReverse } = task;

        // 5. Evaluate Direction Filter (RECEIVED, SENT, BOTH)
        const ruleDirection = rule.direction || 'BOTH';
        if (ruleDirection === 'RECEIVED' && message.fromMe) {
          logger.info({ ruleId: rule.id }, 'Message ignored: rule configured for received/incoming messages only');
          continue;
        }
        if (ruleDirection === 'SENT' && !message.fromMe) {
          logger.info({ ruleId: rule.id }, 'Message ignored: rule configured for sent/outgoing messages only');
          continue;
        }

        // 6. Evaluate Schedule Filter
        if (!this.isWithinSchedule(rule.scheduleConfiguration)) {
          logger.info({ ruleId: rule.id }, 'Message ignored: current time outside permitted forwarding schedule');
          continue;
        }

        // 7. Evaluate Message Type Filter
        if (!this.isPermittedMessageType(message.messageType, rule.messageTypeConfiguration)) {
          logger.info(
            { ruleId: rule.id, messageType: message.messageType },
            'Message ignored: message type not permitted by rule'
          );
          continue;
        }

        // 8. Process Target Destinations
        for (const destConv of targetConversations) {
          // Loop Prevention: Do not forward to same conversation or same phone number
          const cleanDest = destConv.providerConversationId.replace(/@.*$/, '').replace(/\D/g, '');
          const isSamePhone = Boolean(
            cleanDigits &&
            cleanDest &&
            (cleanDigits === cleanDest ||
              (cleanDigits.length === 12 && cleanDigits.startsWith('91') && cleanDigits.slice(2) === cleanDest) ||
              (cleanDest.length === 12 && cleanDest.startsWith('91') && cleanDest.slice(2) === cleanDigits))
          );

          if (
            destConv.id === sourceConversation.id ||
            destConv.providerConversationId === message.sourceJid ||
            isSamePhone
          ) {
            continue;
          }

          // Idempotency check (differentiating reverse path if bidirectional)
          const idempotencyKey = generateIdempotencyKey(
            message.accountId,
            sourceConversation.id,
            message.id,
            `${rule.id}${isReverse ? '_bi_rev' : ''}`,
            destConv.id
          );

          // Check if job already exists
          const existingJob = await prisma.forwardingJob.findUnique({
            where: { idempotencyKey },
          });

          if (existingJob) {
            logger.info({ idempotencyKey }, 'Forwarding job already created, skipping duplicate');
            continue;
          }

          // Create durable job record
          const forwardingJob = await prisma.forwardingJob.create({
            data: {
              forwardingRuleId: rule.id,
              incomingMessageId: incomingMessageRecord.id,
              destinationConversationId: destConv.id,
              status: 'QUEUED',
              idempotencyKey,
            },
            include: {
              forwardingRule: true,
              incomingMessage: true,
              destinationConversation: true,
            },
          });

          emitToAdmin(adminId, 'forwarding:job-queued', {
            job: forwardingJob,
          });

          // Enqueue for processing
          await forwardingQueue.addJob({ forwardingJobId: forwardingJob.id });
        }
      }
    } catch (err: any) {
      logger.error({ err: err.message, messageId: message.id }, 'Error in ForwardingEngine message handling');
    }
  }

  private static isPermittedMessageType(type: string, configJson: string): boolean {
    try {
      const config: MessageTypeConfiguration = JSON.parse(configJson || '{}');
      switch (type) {
        case 'text':
          return config.text !== false;
        case 'image':
          return config.image !== false;
        case 'video':
          return config.video !== false;
        case 'audio':
          return config.audio !== false;
        case 'document':
          return config.document !== false;
        default:
          return false;
      }
    } catch {
      return true;
    }
  }

  private static isWithinSchedule(scheduleJson: string): boolean {
    try {
      const schedule: ScheduleConfiguration = JSON.parse(scheduleJson || '{}');
      if (schedule.allDay) return true;

      const now = new Date();
      const currentDay = now.getDay(); // 0 = Sunday

      if (Array.isArray(schedule.activeDays) && !schedule.activeDays.includes(currentDay)) {
        return false;
      }

      if (schedule.startTime && schedule.endTime) {
        const [startHour, startMin] = schedule.startTime.split(':').map(Number);
        const [endHour, endMin] = schedule.endTime.split(':').map(Number);

        const currentMinutes = now.getHours() * 60 + now.getMinutes();
        const startMinutes = startHour * 60 + startMin;
        const endMinutes = endHour * 60 + endMin;

        if (currentMinutes < startMinutes || currentMinutes > endMinutes) {
          return false;
        }
      }

      return true;
    } catch {
      return true;
    }
  }
}
